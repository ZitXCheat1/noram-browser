// Run after scripts/smoke.js on the same isolated --debug-port 9240 instance.
async(page)=>{
 const assert=(condition,message)=>{if(!condition)throw new Error(message);};
 const until=async(predicate,label)=>{for(let n=0;n<150;n++){const value=await page.evaluate(()=>state);if(predicate(value))return value;await page.waitForTimeout(100);}throw new Error('Timed out: '+label);};
 const cmd=(cmd,extra={})=>page.evaluate(({cmd,extra})=>send(cmd,extra),{cmd,extra});
 const pass=[];
 await page.evaluate(()=>showPanel('settings'));
 await page.getByRole('combobox',{name:'Theme',exact:true}).selectOption('light');
 await until(s=>s.settings.theme==='light','theme');
 assert(await page.evaluate(()=>document.documentElement.dataset.theme)==='light','Light theme applied');
 await page.getByRole('checkbox',{name:'Bookmarks bar',exact:true}).check();
 await until(s=>s.settings.bookmarks_bar,'bookmarks bar');
 assert(await page.locator('#bookmark-bar').isVisible(),'Bookmarks bar visible');
 await page.getByRole('combobox',{name:'Default search engine',exact:true}).selectOption('brave');
 await until(s=>s.settings.search_engine==='brave','default search');pass.push('theme and bookmarks bar','search engine preference');
 await page.evaluate(()=>showPanel('bookmarks'));
 await page.getByRole('button',{name:'Edit bookmark',exact:true}).first().click();
 await page.locator('#bookmark-name').fill('Saved fixture');await page.getByRole('button',{name:'Save bookmark',exact:true}).click();
 await until(s=>s.bookmarks.some(b=>b.title==='Saved fixture'),'bookmark edit');
 await page.getByRole('textbox',{name:'Search bookmarks',exact:true}).fill('not-a-match');
 assert(await page.locator('#collection .collection-row').count()===0,'Bookmark search filtered');
 await page.getByRole('textbox',{name:'Search bookmarks',exact:true}).fill('Saved fixture');
 assert(await page.locator('#collection .collection-row').count()===1,'Bookmark search restored');pass.push('bookmark rename and search');
 await cmd('new');await until(s=>s.tabs.find(t=>t.id===s.active)?.url==='noram://newtab','new tab');
 const tabCheck=await page.evaluate(()=>{
   const nodes=[...document.querySelectorAll('#tabs .tab')],samples=[];
   for(let n=0;n<300;n++){const start=performance.now();update(state);samples.push(performance.now()-start);}
   samples.sort((a,b)=>a-b);
   return {preserved:nodes.every((node,index)=>node===document.querySelectorAll('#tabs .tab')[index]),updates:300,tabs:nodes.length,p95_ms:samples[Math.floor(samples.length*.95)]};
 });assert(tabCheck.preserved,'Unchanged tab nodes retained across updates');pass.push('stable tab DOM under 300 updates');
 const before=(await page.evaluate(()=>state.tabs)).map(t=>t.id);
 await page.locator('#tabs .tab').first().dragTo(page.locator('#tabs .tab').last());
 await until(s=>s.tabs.map(t=>t.id).join(',')!==before.join(','),'drag reorder');pass.push('native tab drag reorder');
 const base=await page.evaluate(()=>({id:state.active,count:state.tabs.length}));
 await cmd('duplicate',{target:base.id});await until(s=>s.tabs.length===base.count+1,'duplicate tab');
 await cmd('close');await until(s=>s.tabs.length===base.count,'close tab');
 await cmd('reopen');await until(s=>s.tabs.length===base.count+1,'reopen tab');
 await cmd('mute');await until(s=>s.tabs.find(t=>t.id===s.active)?.muted,'native mute');pass.push('duplicate close reopen','native tab mute');
 await page.evaluate(()=>showPanel('extensions'));
 const extensionPath='tests/extension';
 await cmd('extension_add',{path:extensionPath});
 let value=await until(s=>s.extensions.some(e=>e.name==='NoRAM QA fixture'&&e.enabled),'extension load');
 const extension=value.extensions.find(e=>e.name==='NoRAM QA fixture');
 await cmd('settings',{settings:{...value.settings,max_live_tabs:4}});
 await cmd('navigate',{url:'http://127.0.0.1:48621/extension'});
 await until(s=>s.tabs.find(t=>t.id===s.active)?.url.includes('/extension')&&!s.tabs.find(t=>t.id===s.active)?.loading,'extension page');
 const websites=await page.context().browser().browserType().connectOverCDP('http://127.0.0.1:9241');
 let content=websites.contexts().flatMap(c=>c.pages()).find(p=>p.url().includes('48621/extension'));
 assert(content,'Extension website exists');
 await content.waitForFunction(()=>document.documentElement.dataset.noramExtension==='working');
 assert(await page.evaluate(()=>document.documentElement.dataset.noramExtension)===undefined,'All-URLs extension did not inject into trusted UI');pass.push('real extension content script','trusted UI isolated from extensions');
 await cmd('extension_toggle',{id:extension.id,enabled:false});
 await until(s=>s.extensions.find(e=>e.id===extension.id)?.enabled===false,'extension disable');
 await cmd('navigate',{url:'http://127.0.0.1:48621/disabled'});await content.waitForURL('**/disabled');await content.waitForLoadState('load');
 assert(await content.evaluate(()=>document.documentElement.dataset.noramExtension)===undefined,'Disabled content script stayed disabled');
 await cmd('extension_toggle',{id:extension.id,enabled:true});await until(s=>s.extensions.find(e=>e.id===extension.id)?.enabled,'extension enable');
 await cmd('navigate',{url:'http://127.0.0.1:48621/enabled'});await content.waitForURL('**/enabled');await content.waitForFunction(()=>document.documentElement.dataset.noramExtension==='working');
 await cmd('extension_remove',{id:extension.id});await until(s=>!s.extensions.some(e=>e.id===extension.id),'extension remove');pass.push('extension disable enable remove');
 await page.evaluate(()=>showPanel('vpn'));value=await until(s=>s.vpn.loaded,'Windows VPN profile enumeration');
 assert(await page.locator('#vpn-list').isVisible(),'VPN status visible');pass.push(value.vpn.profiles?.length?'VPN profiles read without connection':'honest VPN empty state without connection');
 await page.evaluate(()=>showPanel('home'));await until(s=>s.tabs.find(t=>t.id===s.active)?.url==='noram://newtab','return home');
 await page.evaluate(()=>document.fonts.ready);
 assert(await page.evaluate(()=>document.fonts.check('14px Figtree')),'Bundled font loaded');
 const visibleGlyphs=await page.evaluate(()=>Array.from(document.querySelectorAll('svg.ico')).filter(n=>n.getBoundingClientRect().width&&n.getBoundingClientRect().height).map(n=>({href:n.querySelector('use').getAttribute('href'),width:n.getBBox().width})));
 assert(visibleGlyphs.every(n=>n.width>0),'Visible icons have real SVG geometry');pass.push('bundled font','filled SVG icons rendered');
 await websites.close();
 await page.screenshot({path:'output/playwright/v02-home.png'});
 return {passed:pass,tabReconciliation:tabCheck,vpn:value.vpn,visibleSvgCount:visibleGlyphs.length};
}
